#!/usr/bin/env node
// Assemble the Chrome extension from extension/ + the drawing-tool bundle.
//
//   node scripts/build-extension.mjs                -> build/extension/ + build/screshot-<version>.zip
//   node scripts/build-extension.mjs --watch        -> rebuild drawing-tool + build/extension/ on every change
//   node scripts/build-extension.mjs --sync-version -> write package.json version into extension/manifest.json
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'extension');
const TOOL_DIST = path.join(ROOT, 'drawing-tool', 'dist');
const BUILD = path.join(ROOT, 'build');
const OUT = path.join(BUILD, 'extension');

// Files taken from drawing-tool/dist. Source maps are only shipped in watch mode.
const BUNDLE_FILES = ['index.js', 'index.js.LICENSE.txt'];
// Never copy these from extension/: _metadata is generated by the Web Store,
// index.js is the build output of drawing-tool.
const SKIP = new Set(['_metadata', 'index.js', '.DS_Store']);

const args = new Set(process.argv.slice(2));
const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;

if (args.has('--sync-version')) {
  syncManifestVersion();
} else if (args.has('--watch')) {
  watch();
} else {
  assemble();
  const zipFile = path.join(BUILD, `screshot-${version}.zip`);
  zipDir(OUT, zipFile);
  console.log(`✔ ${path.relative(ROOT, zipFile)}`);
}

function syncManifestVersion() {
  const file = path.join(SRC, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  manifest.version = version;
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`✔ extension/manifest.json -> ${version}`);
}

function assemble({ withSourceMap = false } = {}) {
  const bundle = [...BUNDLE_FILES, ...(withSourceMap ? ['index.js.map'] : [])];
  if (!fs.existsSync(path.join(TOOL_DIST, 'index.js'))) {
    throw new Error('drawing-tool/dist/index.js not found, run "npm run build:tool" first');
  }

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.cpSync(SRC, OUT, {
    recursive: true,
    filter: (src) => !SKIP.has(path.basename(src)),
  });
  for (const name of bundle) {
    const from = path.join(TOOL_DIST, name);
    if (fs.existsSync(from)) fs.copyFileSync(from, path.join(OUT, name));
  }

  const manifestFile = path.join(OUT, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  delete manifest.update_url; // added by the Web Store, must not be uploaded
  manifest.version = version;
  fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');

  console.log(`✔ ${path.relative(ROOT, OUT)} (v${version})`);
}

function watch() {
  // Production mode on purpose: dev builds use eval() source maps, which the
  // extension CSP (MV3) blocks.
  const webpack = spawn('npm', ['--prefix', 'drawing-tool', 'run', 'build:watch'], {
    cwd: ROOT,
    stdio: 'inherit',
    shell: true,
  });
  webpack.on('exit', (code) => process.exit(code ?? 0));

  fs.mkdirSync(TOOL_DIST, { recursive: true });
  let timer;
  const rebuild = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        assemble({ withSourceMap: true });
      } catch (err) {
        console.warn(`… waiting: ${err.message}`);
      }
    }, 300);
  };
  fs.watch(SRC, { recursive: true }, rebuild);
  fs.watch(TOOL_DIST, rebuild);
  rebuild();
  console.log('Load unpacked from build/extension, then hit reload in chrome://extensions after changes.');
}

function listFiles(dir, prefix = '') {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      return entry.isDirectory() ? listFiles(path.join(dir, entry.name), rel) : [rel];
    })
    .sort();
}

// Minimal deflate zip writer (no dependencies). Fixed timestamps keep the
// archive byte-for-byte reproducible.
function zipDir(dir, outFile) {
  const DOS_DATE = (0 << 9) | (1 << 5) | 1; // 1980-01-01
  const local = [];
  const central = [];
  let offset = 0;

  for (const rel of listFiles(dir)) {
    const data = fs.readFileSync(path.join(dir, rel));
    const body = zlib.deflateRawSync(data, { level: 9 });
    const crc = zlib.crc32(data);
    const name = Buffer.from(rel, 'utf8');

    const header = Buffer.alloc(30);
    header.writeUInt32LE(0x04034b50, 0);
    header.writeUInt16LE(20, 4); // version needed
    header.writeUInt16LE(0x0800, 6); // UTF-8 names
    header.writeUInt16LE(8, 8); // deflate
    header.writeUInt16LE(0, 10); // time
    header.writeUInt16LE(DOS_DATE, 12);
    header.writeUInt32LE(crc, 14);
    header.writeUInt32LE(body.length, 18);
    header.writeUInt32LE(data.length, 22);
    header.writeUInt16LE(name.length, 26);
    header.writeUInt16LE(0, 28);

    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4); // version made by
    entry.writeUInt16LE(20, 6); // version needed
    entry.writeUInt16LE(0x0800, 8);
    entry.writeUInt16LE(8, 10);
    entry.writeUInt16LE(0, 12);
    entry.writeUInt16LE(DOS_DATE, 14);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(body.length, 20);
    entry.writeUInt32LE(data.length, 24);
    entry.writeUInt16LE(name.length, 28);
    entry.writeUInt32LE(offset, 42);

    local.push(header, name, body);
    central.push(entry, name);
    offset += header.length + name.length + body.length;
  }

  const centralDir = Buffer.concat(central);
  const count = central.length / 2;
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(count, 8);
  end.writeUInt16LE(count, 10);
  end.writeUInt32LE(centralDir.length, 12);
  end.writeUInt32LE(offset, 16);

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, Buffer.concat([...local, centralDir, end]));
}
